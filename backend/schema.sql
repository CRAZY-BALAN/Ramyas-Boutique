CREATE DATABASE IF NOT EXISTS ramyas_boutique CHARACTER SET utf8mb4;
USE ramyas_boutique;
CREATE TABLE IF NOT EXISTS enquiries (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(80) NOT NULL, phone VARCHAR(20) NOT NULL,
  dress_type VARCHAR(120) NOT NULL, message VARCHAR(500) NOT NULL,
  preferred_date DATE NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS admins (
  id INT AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(120) UNIQUE NOT NULL, password_hash VARCHAR(100) NOT NULL
);
